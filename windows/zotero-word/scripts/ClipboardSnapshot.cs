using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Runtime.InteropServices;
using System.Runtime.InteropServices.ComTypes;
using System.Text;
using System.Threading;

// Keep native clipboard formats in memory. No data is deserialized, logged or written to disk.
public sealed class ClipboardSnapshot : IDisposable {
    [DllImport("user32.dll", SetLastError=true)] static extern bool OpenClipboard(IntPtr owner);
    [DllImport("user32.dll")] static extern bool CloseClipboard();
    [DllImport("user32.dll", SetLastError=true)] static extern bool EmptyClipboard();
    [DllImport("user32.dll", SetLastError=true)] static extern uint EnumClipboardFormats(uint after);
    [DllImport("user32.dll", SetLastError=true)] static extern IntPtr GetClipboardData(uint format);
    [DllImport("user32.dll", SetLastError=true)] static extern IntPtr SetClipboardData(uint format, IntPtr data);
    [DllImport("user32.dll", CharSet=CharSet.Unicode)] static extern int GetClipboardFormatName(uint format, StringBuilder name, int length);
    [DllImport("user32.dll", CharSet=CharSet.Unicode)] static extern uint RegisterClipboardFormat(string name);
    [DllImport("user32.dll")] public static extern bool IsClipboardFormatAvailable(uint format);
    [DllImport("user32.dll")] static extern uint GetClipboardSequenceNumber();
    [DllImport("user32.dll")] static extern IntPtr GetClipboardOwner();
    [DllImport("ole32.dll")] static extern IntPtr OleDuplicateData(IntPtr h, ushort format, uint flags);
    [DllImport("ole32.dll")] static extern void ReleaseStgMedium(ref STGMEDIUM medium);
    [DllImport("gdi32.dll", CharSet=CharSet.Unicode)] static extern IntPtr CopyEnhMetaFile(IntPtr h, string file);
    [DllImport("kernel32.dll")] static extern IntPtr GlobalAlloc(uint flags, UIntPtr bytes);
    [DllImport("kernel32.dll")] static extern IntPtr GlobalFree(IntPtr mem);
    [DllImport("kernel32.dll")] static extern IntPtr GlobalLock(IntPtr mem);
    [DllImport("kernel32.dll")] static extern bool GlobalUnlock(IntPtr mem);
    [DllImport("kernel32.dll")] static extern UIntPtr GlobalSize(IntPtr mem);
    readonly Dictionary<uint, IntPtr> saved = new Dictionary<uint, IntPtr>();
    readonly IntPtr owner;
    public uint Sequence { get; private set; }
    public static readonly uint Marker = RegisterClipboardFormat("ZoteroWord.ActiveJob");

    void Open() {
        for (int i = 0; i < 12; i++) {
            if (OpenClipboard(owner)) return;
            Thread.Sleep(25);
        }
        throw new Win32Exception(Marshal.GetLastWin32Error(), "The Windows clipboard is busy.");
    }
    public ClipboardSnapshot(IntPtr window) {
        owner = window;
        Open();
        try {
            for (uint f = EnumClipboardFormats(0); f != 0; f = EnumClipboardFormats(f)) {
                var name = new StringBuilder(255);
                GetClipboardFormatName(f, name, name.Capacity);
                // OLE bookkeeping is regenerated by Windows for the next clipboard owner.
                if (name.ToString() == "Ole Private Data" || name.ToString() == "DataObject") continue;
                if (f == 0x80 || (f >= 0x200 && f <= 0x3ff))
                    throw new InvalidOperationException("The clipboard is holding an owner-managed object. Preserve it before resuming.");
                IntPtr original = GetClipboardData(f);
                uint baseFormat = f == 0x82 ? 2u : f == 0x83 ? 3u : f == 0x8e ? 14u : f;
                IntPtr copy = original == IntPtr.Zero ? IntPtr.Zero : baseFormat == 14 ?
                    CopyEnhMetaFile(original, null) : OleDuplicateData(original, (ushort)baseFormat, 0);
                if (copy == IntPtr.Zero) throw new InvalidOperationException("Could not preserve a clipboard format: " + f);
                saved.Add(f, copy);
            }
            Sequence = GetClipboardSequenceNumber();
        } catch { Dispose(); throw; }
        finally { CloseClipboard(); }
    }
    static void SetText(uint format, string text) {
        byte[] bytes = Encoding.Unicode.GetBytes(text + "\0");
        IntPtr h = GlobalAlloc(0x42, (UIntPtr)(uint)bytes.Length);
        if (h == IntPtr.Zero) throw new OutOfMemoryException();
        try {
            IntPtr p = GlobalLock(h);
            if (p == IntPtr.Zero) throw new Win32Exception();
            try { Marshal.Copy(bytes, 0, p, bytes.Length); }
            finally { GlobalUnlock(h); }
            if (SetClipboardData(format, h) == IntPtr.Zero) throw new Win32Exception();
            h = IntPtr.Zero;
        } finally { if (h != IntPtr.Zero) GlobalFree(h); }
    }
    void RestoreLocked() {
        if (!EmptyClipboard()) throw new Win32Exception();
        foreach (uint f in new List<uint>(saved.Keys)) {
            if (SetClipboardData(f, saved[f]) == IntPtr.Zero) throw new Win32Exception();
            saved.Remove(f);  // Windows owns successfully restored handles.
        }
    }
    public uint Stage(uint expected, string text, string job) {
        Open();
        try {
            if (GetClipboardSequenceNumber() != expected) throw new InvalidOperationException("The clipboard changed before pasting.");
            if (!EmptyClipboard()) throw new Win32Exception();
            try { SetText(13, text); SetText(Marker, job); }
            catch { RestoreLocked(); throw; }
        } finally { CloseClipboard(); }

        // Windows can publish a new clipboard sequence on release.
        // Bind the published sequence to our HWND and the exact staged data.
        return ConfirmStage(text, job);
    }
    public uint ConfirmStage(string text, string job) {
        Open();
        try {
            if (GetClipboardOwner() != owner || !MatchesText(Marker, job) || !MatchesText(13, text))
                throw new InvalidOperationException("Clipboard ownership or staged content changed before paste.");
            return GetClipboardSequenceNumber();
        } finally { CloseClipboard(); }
    }
    static bool MatchesText(uint format, string expected) {
        IntPtr handle = GetClipboardData(format);
        if (handle == IntPtr.Zero || GlobalSize(handle).ToUInt64() < ((ulong)expected.Length + 1) * 2) return false;
        IntPtr pointer = GlobalLock(handle);
        if (pointer == IntPtr.Zero) return false;
        try { return Marshal.ReadInt16(pointer, expected.Length * 2) == 0 &&
            string.Equals(Marshal.PtrToStringUni(pointer, expected.Length), expected, StringComparison.Ordinal); }
        finally { GlobalUnlock(handle); }
    }
    public void Restore(uint expected) {
        Open();
        try { if (GetClipboardSequenceNumber() == expected) RestoreLocked(); }
        finally { CloseClipboard(); }
    }
    public void Dispose() {
        foreach (var pair in saved) {
            uint f = pair.Key;
            TYMED kind = (f == 2 || f == 9 || f == 0x82) ? TYMED.TYMED_GDI :
                (f == 3 || f == 0x83) ? TYMED.TYMED_MFPICT : (f == 14 || f == 0x8e) ? TYMED.TYMED_ENHMF : TYMED.TYMED_HGLOBAL;
            var medium = new STGMEDIUM { tymed = kind, unionmember = pair.Value, pUnkForRelease = null };
            ReleaseStgMedium(ref medium);
        }
        saved.Clear();
    }
}
